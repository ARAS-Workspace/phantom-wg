from __future__ import annotations

from core.commands import FORCE
from stack.dev.libs import keys

ABOUT = "Generate WireGuard keypair"
ARGUMENTS = (FORCE,)
USAGE = "gen-keys [-f]"


def run(force: bool) -> None:
    if keys.present():
        if not force:
            print("WG keys already exist. Use -f to overwrite.")
            return
        print("Overwriting WG keys (--force)...")
    keys.generate()
