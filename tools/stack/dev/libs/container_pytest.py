from __future__ import annotations

from collections.abc import Sequence

from stack.dev.libs import compose


def run(flags: Sequence[str], args: Sequence[str]) -> None:
    """Runs pytest on args, or on tests/ when there are none."""
    targets = () if args else ("tests/",)
    compose.run("exec", compose.DAEMON, "python", "-m", "pytest", *targets, *flags, *args)
