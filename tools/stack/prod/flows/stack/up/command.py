from __future__ import annotations

from stack.prod.libs import compose, environment, gates, host, terazi

ABOUT = "Start production stack"


def run() -> None:
    gates.enforce(host.SETUP_GATES)
    environment.require()

    subnet = terazi.pending()
    print("Starting stack...")
    compose.run("up", "-d", env={"DEFAULT_IPV4_SUBNET": subnet} if subnet else None)
    terazi.forget()

    compose.run("ps")
    print("Stack started.")
