from __future__ import annotations

from core.commands import FORCE
from stack.prod.libs import gates, host, keys

ABOUT = "Generate WireGuard keypair"
ARGUMENTS = (FORCE,)
USAGE = "gen-keys [-f]"


def run(force: bool) -> None:
    gates.enforce(host.DOCKER_GATES)
    if force:
        print("Overwriting WG keys (--force)...")
        keys.generate()
    elif keys.present():
        print("WG keys already exist. Use -f to overwrite.")
    else:
        keys.provide()
