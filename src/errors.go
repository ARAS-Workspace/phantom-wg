package main

import "errors"

// codeError is an error with the code its export returns; the guard
// records both as the calling thread's last error (guards.go).
type codeError struct {
	code int32
	err  error
}

func (e *codeError) Error() string { return e.err.Error() }
func (e *codeError) Unwrap() error { return e.err }

// withCode gives err the code its export returns for it.
func withCode(code int32, err error) error {
	return &codeError{code: code, err: err}
}

// errTunCreate is in the error newPersistentDevice returns when the TUN
// device cannot be created.
var errTunCreate = errors.New("create tun")
